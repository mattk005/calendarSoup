func (cfg *LocalCfg) handlerGetCal(w http.ResponseWriter, req *http.Request) {
	wfmUUID, err := uuid.Parse(req.PathValue("wfmID"))
	if err != nil {
		respondWithError(w, http.StatusUnauthorized, "invalid wfmUUID", err)
		return
	}
	dbUser, err := cfg.Queries.GetUserBywfmID(req.Context(), wfmUUID.String())
	fmt.Println(dbUser)
	if err != nil {
		respondWithError(w, http.StatusUnauthorized, "couldn't get user from database", err)
		return
	}
	cal, err := cfg.getCal(wfmUUID.String())
	if err != nil {
		respondWithError(w, http.StatusBadRequest, "couldn't get public cal from WFM", err)
		return
	}
	events := cal.Events()
	if len(events) == 0 {
		respondWithError(w, http.StatusInternalServerError, "wfmCal has no events", err)
		return
	}
	minTime, maxTime := getMinMaxTime(events)
	tx, err := cfg.DB.BeginTx(req.Context(), nil)
	if err != nil {
		respondWithError(w, http.StatusInternalServerError, "failed to begin database transaction", err)
		return
	}
	defer tx.Rollback()
	qtx := cfg.Queries.WithTx(tx)
	if err := qtx.DeleteEventsByDateRange(req.Context(), database.DeleteEventsByDateRangeParams{
		MinDate: minTime,
		MaxDate: maxTime,
	}); err != nil {
		respondWithError(w, http.StatusInternalServerError, "couldn't delete events in date range", err)
		return
	}
	for _, e := range events {
		addEventParams, err := getEventParams(e)
		if err != nil {
			respondWithError(w, http.StatusInternalServerError, "failed to fill addEventParams", err)
		}
		addEventParams.UserID = dbUser.ID
		err = qtx.AddEvent(req.Context(), addEventParams)
		if err != nil {
			respondWithError(w, http.StatusInternalServerError, "couldn't add event", err)
		}
	}
	if err := tx.Commit(); err != nil {
		respondWithError(w, http.StatusInternalServerError, "failed to commit events to DB", err)
		return
	}
}

func getEventParams(e *ics.VEvent) (database.AddEventParams, error) {
	summary := ""
	if prop := e.GetProperty(ics.ComponentPropertySummary); prop != nil {
		summary = prop.Value
	}
	startAt, err := e.GetStartAt()
	if err != nil {
		return database.AddEventParams{}, nil
	}
	endAt, err := e.GetEndAt()
	if err != nil {
		return database.AddEventParams{}, nil
	}
	desciption := ""
	if prop := e.GetProperty(ics.ComponentPropertyDescription); prop != nil {
		desciption = prop.Value
	}
	location := ""
	if prop := e.GetProperty(ics.ComponentPropertyLocation); prop != nil {
		desciption = prop.Value
	}
	result := database.AddEventParams{
		ID:         e.Id(),
		Summary:    summary,
		EventStart: startAt,
		EventEnd:   endAt,
		Description: sql.NullString{
			String: desciption,
			Valid:  true,
		},
		Location: sql.NullString{
			String: location,
			Valid:  true,
		},
		UserID: nil,
	}
	return result, nil
}

func getMinMaxTime(events []*ics.VEvent) (time.Time, time.Time) {
	start, _ := events[0].GetStartAt()
	end, _ := events[0].GetEndAt()
	minTime, maxTime := start, end
	for _, e := range events {
		start, _ = e.GetStartAt()
		if start.Before(minTime) {
			minTime = start
		}
		end, _ = e.GetEndAt()
		if end.After(maxTime) {
			maxTime = end
		}
	}
	return minTime, maxTime
}

func (cfg *LocalCfg) getCal(wfmUUID string) (*ics.Calendar, error) {
	var cal *ics.Calendar
	url, err := url.Parse(cfg.BaseURL)
	if err != nil {
		fmt.Println("BaseURL is busted")
		return cal, err
	}
	url = url.JoinPath("public", "ical", wfmUUID, "myschedule.ics")
	req, err := http.NewRequest("GET", url.String(), nil)
	if err != nil {
		return cal, err
	}
	resp, err := cfg.Client.Do(req)
	if err != nil {
		return cal, err
	}
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("unexpected status code from WFM: %d", resp.StatusCode)
	}
	defer resp.Body.Close()
	cal, err = ics.ParseCalendar(cleanICS(resp.Body))
	if err != nil {
		return cal, err
	}
	return cal, nil
}

func cleanICS(r io.Reader) io.Reader {
	var buf bytes.Buffer
	scanner := bufio.NewScanner(r)
	for scanner.Scan() {
		line := scanner.Text()
		trimmed := strings.TrimSpace(line)

		// Skip empty property lines generated by Infor WFM
		if trimmed == "DTSTART:" || trimmed == "DTEND:" {
			continue
		}
		buf.WriteString(line + "\r\n")
	}
	return &buf
}
